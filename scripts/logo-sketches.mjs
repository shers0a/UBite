#!/usr/bin/env node
/* Puts the AI logo sketches (assets/_raw/mark-*) into the design system's logo picker:
   each sketch becomes a 480px WebP in assets/explorations/logo/ (recorded in the manifest as
   status "exploration") and an entry in explorations/logo-ai.js, which logo-picker.html shows
   under "Explorare AI". Re-run after generating more sketches. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const RAW = path.join(ROOT, 'assets', '_raw');
const OUT = path.join(ROOT, 'assets', 'explorations', 'logo');
const PICKER = path.join(ROOT, '.claude', 'skills', 'ubite-design', 'explorations');

// Which drawn concept each sketch argues for, in the picker's own words.
const CONCEPTS = {
  'tray-queue': ['Tava-U și coada', 'Schiță AI pentru A: tava văzută din lateral, cu trei capete la coadă.'],
  'bowl-level': ['Bolul cu nivel', 'Schiță AI pentru N1: un bol care se umple ca un indicator.'],
  'compartment-tray': ['Tava cu compartimente', 'Schiță AI pentru N2: tava de cantină văzută de sus.'],
  'plate-clock': ['Farfuria-ceas', 'Schiță AI pentru N3: farfurie și cadran, felia arată așteptarea.'],
  'ub-monogram': ['Monograma UB', 'Schiță AI pentru N4: U și B pe o singură bară.'],
  'spoon-u': ['Lingura-U', 'Schiță AI pentru N10: lingura care se îndoaie în litera U.'],
  'bitten-u': ['U-ul mușcat', 'Schiță AI pentru N5: un U cu o mușcătură.'],
  'flap-tile': ['Paleta de afișaj', 'Schiță AI pentru N8: paleta unui panou de plecări cu litera U.'],
};

// node scripts/logo-sketches.mjs --skip s54006,s54007   leaves rejected seeds out of the picker
const skipArg = process.argv.indexOf('--skip');
const SKIP = new Set(skipArg > 0 ? process.argv[skipArg + 1].split(',') : []);

fs.mkdirSync(OUT, { recursive: true });
const entries = [];
let n = 0;
for (const dir of fs.readdirSync(RAW).filter((d) => d.startsWith('mark-')).sort()) {
  const key = dir.replace(/^mark-/, '');
  const [name, concept] = CONCEPTS[key] || [key, 'Schiță AI.'];
  for (const f of fs.readdirSync(path.join(RAW, dir)).filter((x) => x.endsWith('.jpg') && ![...SKIP].some((k) => x.includes(k))).sort()) {
    n++;
    const out = path.join(OUT, f.replace(/\.jpg$/, '.webp'));
    const relOut = path.relative(ROOT, out).split(path.sep).join('/');
    execFileSync(process.execPath, [path.join(ROOT, 'scripts', 'asset.mjs'), 'promote', path.join(RAW, dir, f), relOut, '--status', 'exploration', '--width', '480']);
    entries.push({ id: `AI${n}`, name, concept, src: `../../../../${relOut}` });
  }
}
fs.writeFileSync(path.join(PICKER, 'logo-ai.js'),
  `/* Generated by scripts/logo-sketches.mjs — AI logo sketches shown in logo-picker.html. */\nwindow.UBITE_AI_CONCEPTS = ${JSON.stringify(entries, null, 2)};\n`);
console.log(`✓ ${entries.length} sketches → assets/explorations/logo/ and explorations/logo-ai.js`);
